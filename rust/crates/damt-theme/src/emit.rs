//! The output generators: Slint, CSS and Rust.
//!
//! All three walk the same resolved [`Tokens`], in name order, so the outputs stay in lockstep.

use crate::{Rgba, Tokens};

/// Formats a px value the way each language wants a float literal ("8", "2.5").
fn px(value: f64) -> String {
    if value.fract() == 0.0 {
        format!("{value:.1}")
    } else {
        format!("{value}")
    }
}

/// `text-muted` → `TEXT_MUTED` (for Rust constants).
fn const_name(name: &str) -> String {
    name.to_uppercase().replace('-', "_")
}

/// Generates `theme.slint`.
pub(crate) fn slint(tokens: &Tokens) -> String {
    let mut out = String::new();
    out.push_str("// Generated by damt-theme from tokens.toml. DO NOT EDIT.\n");
    out.push_str(
        "// Regenerate: cargo run -p damt-theme --example gen -- <tokens.toml> <out_dir>\n",
    );
    out.push_str("export global Theme {\n");
    out.push_str("    // Set by the app: true switches every colour to its dark value.\n");
    out.push_str("    in-out property <bool> dark: false;\n");
    for (name, pair) in tokens.colors() {
        out.push_str(&format!(
            "    out property <color> {}: dark ? {} : {};\n",
            name,
            pair.dark.to_hex(),
            pair.light.to_hex()
        ));
    }
    for (name, value) in tokens.radii() {
        out.push_str(&format!(
            "    out property <length> radius-{}: {}px;\n",
            name,
            px(value)
        ));
    }
    for (name, value) in tokens.spaces() {
        out.push_str(&format!(
            "    out property <length> space-{}: {}px;\n",
            name,
            px(value)
        ));
    }
    for (name, value) in tokens.font_sizes() {
        out.push_str(&format!(
            "    out property <length> font-size-{}: {}px;\n",
            name,
            px(value)
        ));
    }
    out.push_str("}\n");
    out
}

/// Generates `tokens.css`.
pub(crate) fn css(tokens: &Tokens) -> String {
    let mut out = String::new();
    out.push_str("/* Generated by damt-theme from tokens.toml. DO NOT EDIT.\n");
    out.push_str(
        "   Regenerate: cargo run -p damt-theme --example gen -- <tokens.toml> <out_dir> */\n",
    );

    out.push_str(":root {\n");
    for (name, pair) in tokens.colors() {
        out.push_str(&format!("  --color-{}: {};\n", name, pair.light.to_hex()));
    }
    for (name, value) in tokens.radii() {
        out.push_str(&format!("  --radius-{}: {}px;\n", name, px(value)));
    }
    for (name, value) in tokens.spaces() {
        out.push_str(&format!("  --space-{}: {}px;\n", name, px(value)));
    }
    for (name, value) in tokens.font_sizes() {
        out.push_str(&format!("  --font-size-{}: {}px;\n", name, px(value)));
    }
    out.push_str("}\n");

    // The dark values, under both selectors the websites use: the system scheme
    // (unless the visitor forced light) and an explicit data-theme="dark".
    out.push_str("@media (prefers-color-scheme: dark) {\n  :root:not([data-theme=\"light\"]) {\n");
    push_dark_colors(&mut out, tokens, "    ");
    out.push_str("  }\n}\n");
    out.push_str(":root[data-theme=\"dark\"] {\n");
    push_dark_colors(&mut out, tokens, "  ");
    out.push_str("}\n");
    out
}

fn push_dark_colors(out: &mut String, tokens: &Tokens, indent: &str) {
    for (name, pair) in tokens.colors() {
        out.push_str(&format!(
            "{indent}--color-{}: {};\n",
            name,
            pair.dark.to_hex()
        ));
    }
}

/// Generates `tokens.rs`.
pub(crate) fn rust(tokens: &Tokens) -> String {
    let mut out = String::new();
    out.push_str("// Generated by damt-theme from tokens.toml. DO NOT EDIT.\n");
    out.push_str(
        "// Regenerate: cargo run -p damt-theme --example gen -- <tokens.toml> <out_dir>\n",
    );
    out.push_str("#![allow(non_upper_case_globals)]\n\n");
    out.push_str("use damt_theme::Rgba;\n\n");
    for (name, pair) in tokens.colors() {
        out.push_str(&format!(
            "pub const {}_LIGHT: Rgba = {};\n",
            const_name(name),
            rust_rgba(pair.light)
        ));
        out.push_str(&format!(
            "pub const {}_DARK: Rgba = {};\n",
            const_name(name),
            rust_rgba(pair.dark)
        ));
    }
    out.push('\n');
    for (name, value) in tokens.radii() {
        out.push_str(&format!(
            "pub const RADIUS_{}: f32 = {};\n",
            const_name(name),
            px(value)
        ));
    }
    for (name, value) in tokens.spaces() {
        out.push_str(&format!(
            "pub const SPACE_{}: f32 = {};\n",
            const_name(name),
            px(value)
        ));
    }
    for (name, value) in tokens.font_sizes() {
        out.push_str(&format!(
            "pub const FONT_SIZE_{}: f32 = {};\n",
            const_name(name),
            px(value)
        ));
    }
    out
}

/// `Rgba { r: 0xF6, g: 0xF7, b: 0xF5, a: 0xFF }`
fn rust_rgba(c: Rgba) -> String {
    format!(
        "Rgba {{ r: 0x{:02X}, g: 0x{:02X}, b: 0x{:02X}, a: 0x{:02X} }}",
        c.r, c.g, c.b, c.a
    )
}
